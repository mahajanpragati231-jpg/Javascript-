 let mood = "happy";

switch (mood) {
    case "happy":
        console.log(" Keep smiling!");
        break;

    case "sad":
        console.log(" Everything will be okay.");
        break;

    case "angry":
        console.log(" Take a deep breath.");
        break;

    case "tired":
        console.log(" Take some rest.");
        break;

    default:
        console.log(" Have a nice day!");
}